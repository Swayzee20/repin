import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

export const seededColumns = ["name", "slug", "category", "equipment"];
export const omittedCsvColumns = [
  "group",
  "types",
  "default_measure",
  "aliases",
  "notes",
];

export const seedDir = dirname(fileURLToPath(import.meta.url));
export const csvPath = resolve(seedDir, "starter-exercises.csv");
export const sqlPath = resolve(seedDir, "starter-movements.sql");

const kebabCaseSlug = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;

export function parseCsv(text) {
  const rows = [];
  let row = [];
  let field = "";
  let inQuotes = false;
  const input = text.replace(/^\uFEFF/, "");

  for (let index = 0; index < input.length; index += 1) {
    const character = input[index];

    if (inQuotes) {
      if (character === '"') {
        if (input[index + 1] === '"') {
          field += '"';
          index += 1;
        } else {
          inQuotes = false;
        }
      } else {
        field += character;
      }
      continue;
    }

    if (character === '"') {
      inQuotes = true;
      continue;
    }

    if (character === ",") {
      row.push(field);
      field = "";
      continue;
    }

    if (character === "\n" || character === "\r") {
      if (character === "\r" && input[index + 1] === "\n") {
        index += 1;
      }
      row.push(field);
      if (row.some((cell) => cell.length > 0)) {
        rows.push(row);
      }
      row = [];
      field = "";
      continue;
    }

    field += character;
  }

  if (field.length > 0 || row.length > 0) {
    row.push(field);
    if (row.some((cell) => cell.length > 0)) {
      rows.push(row);
    }
  }

  if (rows.length === 0) {
    throw new Error("Starter exercises CSV is empty");
  }

  const [header, ...data] = rows;
  return data.map((cells) => {
    const record = Object.fromEntries(
      header.map((key, index) => [key, cells[index] ?? ""]),
    );
    return record;
  });
}

export function sqlLiteral(value) {
  return `'${value.replaceAll("'", "''")}'`;
}

export function generateStarterMovementsSql(rows) {
  const values = rows
    .map((row) => {
      return `  (${sqlLiteral(row.name)}, ${sqlLiteral(row.slug)}, ${sqlLiteral(row.category)}, ${sqlLiteral(row.equipment)})`;
    })
    .join(",\n");

  return `/*
  Starter movement catalog (PR L3).
  Source: packages/db/seed/starter-exercises.csv
  Regenerated by: node packages/db/seed/generate-starter-movements.mjs

  Safe to run more than once. Existing rows are left unchanged.
  movements.slug already has UNIQUE constraint movements_slug_unique, so
  ON CONFLICT (slug) DO NOTHING skips any slug that is already present.

  This is data only — not a numbered Drizzle migration. Apply by hand to
  live Supabase the same way as Drizzle SQL (SQL editor, or psql against
  DATABASE_URL on a role that bypasses RLS).
*/

insert into public.movements (name, slug, category, equipment)
values
${values}
on conflict (slug) do nothing;
`;
}

export function stripSqlComments(sql) {
  return sql.replace(/\/\*[\s\S]*?\*\//g, "").trim();
}

export function parseSeedSql(sql) {
  const body = stripSqlComments(sql).replace(/;\s*$/, "");
  const insertMatch = body.match(
    /^insert\s+into\s+public\.movements\s*\(\s*name\s*,\s*slug\s*,\s*category\s*,\s*equipment\s*\)\s*values\s*([\s\S]+)\s*on\s+conflict\s*\(\s*slug\s*\)\s*do\s+nothing\s*$/i,
  );

  if (!insertMatch) {
    throw new Error(
      "Seed SQL is not an idempotent insert into public.movements (name, slug, category, equipment) on conflict (slug) do nothing",
    );
  }

  return parseValueTuples(insertMatch[1]);
}

export function isKebabCaseSlug(slug) {
  return kebabCaseSlug.test(slug);
}

function parseValueTuples(valuesSql) {
  const rows = [];
  let index = 0;
  const source = valuesSql.trim();

  while (index < source.length) {
    while (index < source.length && /[\s,]/.test(source[index])) {
      index += 1;
    }
    if (index >= source.length) {
      break;
    }
    if (source[index] !== "(") {
      throw new Error(`Expected ( in VALUES at index ${index}`);
    }
    index += 1;

    const cells = [];
    while (index < source.length) {
      while (index < source.length && /\s/.test(source[index])) {
        index += 1;
      }
      if (source[index] !== "'") {
        throw new Error(`Expected a string literal at index ${index}`);
      }
      index += 1;
      let value = "";
      while (index < source.length) {
        if (source[index] === "'") {
          if (source[index + 1] === "'") {
            value += "'";
            index += 2;
            continue;
          }
          index += 1;
          break;
        }
        value += source[index];
        index += 1;
      }
      cells.push(value);

      while (index < source.length && /\s/.test(source[index])) {
        index += 1;
      }
      if (source[index] === ",") {
        index += 1;
        continue;
      }
      if (source[index] === ")") {
        index += 1;
        break;
      }
      throw new Error(`Unexpected token in VALUES tuple at index ${index}`);
    }

    if (cells.length !== seededColumns.length) {
      throw new Error(
        `Expected ${seededColumns.length} columns, got ${cells.length}`,
      );
    }

    rows.push({
      name: cells[0],
      slug: cells[1],
      category: cells[2],
      equipment: cells[3],
    });
  }

  return rows;
}
